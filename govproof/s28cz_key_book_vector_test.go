// keyBookVector is the shared key-book vector (testdata/simulator/key-book.json): a key book proven at its partition's Directory-recorded root,
// generated by infrix-core (pkg/l0/proofcapture TestS28czKeyPageOperandsAreProvenAtTheDirectoryRecordedRoot with S28CZ_WRITE_KEY_BOOK_VECTOR=1,
// infrix-core L3260) on an in-process embedded network and vendored here byte-identical: verified only against its own pin, never a Kermit claim.
// The book is a genesis key book that never signed, so it lists no chains (the zero chain hash).
type keyBookVector struct {
	Proof     govproof.KeyBookProof `json:"proof"`
	Pin       consensus.Pin         `json:"pin"`
	Book      string                `json:"book"`
	PageCount uint64                `json:"pageCount"`
}

func loadKeyBook(t *testing.T) *keyBookVector {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "simulator", "key-book.json"))
	if err != nil {
		t.Fatal(err)
	}
	var v keyBookVector
	if err := json.Unmarshal(b, &v); err != nil {
		t.Fatal(err)
	}
	return &v
}

// VerifyKeyBook over core's vector establishes the key book and its proven page count at the anchored height (actor::has_key's proof that a page
// past the count does not exist); VerifyKeyPage refuses it (it is not a key page); and every effective mutation of every field is refused, the
// census covering every field of the proof type.
func TestS28czTheSharedKeyBookVectorVerifiesAndEveryMutationIsRefused(t *testing.T) {
	v := loadKeyBook(t)
	opts := l0proof.Options{OverridePin: &v.Pin}
	r := govproof.VerifyKeyBook(&v.Proof, opts)
	if !r.Verified || r.Form != govproof.FormDirectoryRoot || !strings.EqualFold(r.Book.URL, v.Book) || r.Book.PageCount != v.PageCount || r.Height != v.Proof.Height {
		t.Fatalf("the vector's verdict: %+v", r)
	}
	if len(v.Proof.PageState.Chains) != 0 {
		t.Fatalf("premise: the vector's book lists %d chains; it is a genesis book that never signed", len(v.Proof.PageState.Chains))
	}
	if pr := govproof.VerifyKeyPage(&v.Proof, opts); pr.Verified {
		t.Fatal("a key book's proof verified as a key page")
	}
	if kermit, err := l0proof.CompiledPin("kermit"); err == nil {
		if kr := govproof.VerifyKeyBook(&v.Proof, l0proof.Options{OverridePin: &kermit}); kr.Verified {
			t.Fatal("the local-embedded vector verified under Kermit's pin")
		}
	}

	p := cloneKP(t, &v.Proof)
	before := cloneKP(t, p)
	covered := map[string]bool{}
	total := 0
	var ms []tamper.Mutation
	tamper.Mutations(reflect.ValueOf(p).Elem(), "", &ms)
	for _, m := range ms {
		m.Apply()
		if !sameKP(t, p, before) {
			if r := govproof.VerifyKeyBook(p, opts); r.Verified {
				t.Errorf("%s of %s still verifies", m.Kind, m.Path)
			}
			covered[tamper.TypePath(m.Path)] = true
			total++
		}
		m.Undo()
	}
	if r := govproof.VerifyKeyBook(p, opts); !r.Verified {
		t.Fatalf("the restored proof no longer verifies: %s", r.Reason)
	}
	// the ledger form's fields are absent from a directory-root proof, and an account that lists no chains has none to mutate: the census is over
	// the fields this proof carries
	if total == 0 {
		t.Fatal("no effective mutation")
	}
	for _, f := range []string{"Incarnation", "Page", "Height", "Partition", "PageState.MainState", "PartitionAnchor", "Directory", "Consensus"} {
		hit := false
		for path := range covered {
			if strings.HasPrefix(path, f) {
				hit = true
			}
		}
		if !hit {
			t.Fatalf("no effective mutation of %s (covered %d paths)", f, len(covered))
		}
	}
	t.Logf("%d mutations over %d field paths, every one refused", total, len(covered))
}
